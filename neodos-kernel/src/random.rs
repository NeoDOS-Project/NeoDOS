//! Kernel CSPRNG and the `\Device\Random` object (#712 / M8).
//!
//! The pool is a ChaCha20-based DRBG. It is seeded from **RDSEED** when the
//! CPU has it, falls back to **RDRAND**, and — on CPUs with neither — mixes the
//! TSC with a counter. Only the hardware sources are a vetted CSPRNG seed, so
//! [`RandomCaps`] reports them separately and TLS fails closed when neither is
//! present (a TSC-only pool is usable but not a cryptographic guarantee).
//!
//! Userspace reads bytes with `ObInfoClass::Random = 48` and the flags with
//! `RandomCaps = 49`. The pool reseeds every 1 MiB or 1 s of uptime.

use lazy_static::lazy_static;
use spin::Mutex;

/// Largest single read, so one syscall cannot drain the pool or spin forever.
pub const MAX_READ: usize = 4096;
/// `\Device\Random` native id (unique within `ObType::Device`).
pub const DEVICE_NATIVE_ID: u64 = 3;
/// Reseed after this many generated bytes.
const RESEED_BYTES: usize = 1024 * 1024;
/// Reseed after this much wall time.
const RESEED_US: u64 = 1_000_000;

/// Random source capabilities (`ObInfoClass::RandomCaps`).
#[repr(C)]
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct RandomCaps {
    /// 1 when the CPU implements RDRAND.
    pub hw_rdrand: u8,
    /// 1 when the CPU implements RDSEED.
    pub hw_rdseed: u8,
    /// 1 once the pool has been seeded.
    pub pool_ready: u8,
    pub _pad: u8,
}

/// A bounded request could not be served.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum RngError {
    /// Request larger than [`MAX_READ`].
    TooLarge,
    /// The pool could not be generated from.
    Unavailable,
}

// ── ChaCha20 ──

const CONSTANTS: [u32; 4] = [0x6170_7865, 0x3320_646e, 0x7962_2d32, 0x6b20_6574];

#[inline]
fn quarter_round(s: &mut [u32; 16], a: usize, b: usize, c: usize, d: usize) {
    s[a] = s[a].wrapping_add(s[b]);
    s[d] = (s[d] ^ s[a]).rotate_left(16);
    s[c] = s[c].wrapping_add(s[d]);
    s[b] = (s[b] ^ s[c]).rotate_left(12);
    s[a] = s[a].wrapping_add(s[b]);
    s[d] = (s[d] ^ s[a]).rotate_left(8);
    s[c] = s[c].wrapping_add(s[d]);
    s[b] = (s[b] ^ s[c]).rotate_left(7);
}

/// One ChaCha20 keystream block (`counter` in word 12, 96-bit nonce in 13..16).
pub(crate) fn chacha20_block(key: &[u8; 32], counter: u32, nonce: &[u8; 12]) -> [u8; 64] {
    let mut state = [0u32; 16];
    state[..4].copy_from_slice(&CONSTANTS);
    for i in 0..8 {
        state[4 + i] = u32::from_le_bytes([
            key[i * 4],
            key[i * 4 + 1],
            key[i * 4 + 2],
            key[i * 4 + 3],
        ]);
    }
    state[12] = counter;
    for i in 0..3 {
        state[13 + i] = u32::from_le_bytes([
            nonce[i * 4],
            nonce[i * 4 + 1],
            nonce[i * 4 + 2],
            nonce[i * 4 + 3],
        ]);
    }
    let mut work = state;
    for _ in 0..10 {
        quarter_round(&mut work, 0, 4, 8, 12);
        quarter_round(&mut work, 1, 5, 9, 13);
        quarter_round(&mut work, 2, 6, 10, 14);
        quarter_round(&mut work, 3, 7, 11, 15);
        quarter_round(&mut work, 0, 5, 10, 15);
        quarter_round(&mut work, 1, 6, 11, 12);
        quarter_round(&mut work, 2, 7, 8, 13);
        quarter_round(&mut work, 3, 4, 9, 14);
    }
    let mut out = [0u8; 64];
    for i in 0..16 {
        let word = work[i].wrapping_add(state[i]);
        out[i * 4..i * 4 + 4].copy_from_slice(&word.to_le_bytes());
    }
    out
}

// ── DRBG ──

struct Drbg {
    key: [u8; 32],
    nonce: [u8; 12],
    counter: u32,
    block: [u8; 64],
    used: usize,
    seeded: bool,
    bytes_since_reseed: usize,
    last_reseed_us: u64,
}

impl Drbg {
    const fn new() -> Self {
        Drbg {
            key: [0u8; 32],
            nonce: [0u8; 12],
            counter: 0,
            block: [0u8; 64],
            used: 64,
            seeded: false,
            bytes_since_reseed: 0,
            last_reseed_us: 0,
        }
    }

    fn seed(&mut self) {
        fill_material(&mut self.key);
        fill_material(&mut self.nonce);
        self.counter = 0;
        self.block = [0u8; 64];
        self.used = 64;
        self.seeded = true;
        self.bytes_since_reseed = 0;
        self.last_reseed_us = uptime_us();
    }

    fn ensure_seeded(&mut self) {
        if !self.seeded {
            self.seed();
        }
    }

    fn reseed_if_due(&mut self) {
        let due = self.bytes_since_reseed >= RESEED_BYTES
            || uptime_us().saturating_sub(self.last_reseed_us) >= RESEED_US;
        if due {
            self.seed();
        }
    }

    fn next_block(&mut self) {
        self.block = chacha20_block(&self.key, self.counter, &self.nonce);
        self.counter = self.counter.wrapping_add(1);
        self.used = 0;
    }
}

lazy_static! {
    static ref DRBG: Mutex<Drbg> = Mutex::new(Drbg::new());
}

/// Monotonic microseconds, or 0 before the TSC is calibrated.
fn uptime_us() -> u64 {
    let (ms, _hz) = crate::hal::uptime_ms();
    ms.saturating_mul(1000)
}

/// Fill `out` with seed material: RDSEED, else RDRAND, else TSC+counter.
fn fill_material(out: &mut [u8]) {
    let mut i = 0usize;
    let mut mix = 0u64;
    while i < out.len() {
        let value = crate::hal::rdseed()
            .or_else(crate::hal::rdrand)
            .unwrap_or_else(|| {
                // No hardware source: a TSC/counter mix. `RandomCaps` tells
                // callers this is not a vetted CSPRNG seed.
                mix = mix.wrapping_add(0x9E37_79B9_7F4A_7C15);
                crate::boot_benchmark::rdtsc()
                    ^ mix
                    ^ (i as u64).wrapping_mul(0xD1B5_4A32_D192_ED03)
            });
        let bytes = value.to_le_bytes();
        let take = (out.len() - i).min(8);
        out[i..i + take].copy_from_slice(&bytes[..take]);
        i += take;
    }
}

/// Fill `buf` with random bytes (at most [`MAX_READ`]).
pub fn fill(buf: &mut [u8]) -> Result<(), RngError> {
    if buf.len() > MAX_READ {
        return Err(RngError::TooLarge);
    }
    if buf.is_empty() {
        return Ok(());
    }
    let mut drbg = DRBG.lock();
    drbg.ensure_seeded();
    drbg.reseed_if_due();
    let mut written = 0usize;
    while written < buf.len() {
        if drbg.used >= drbg.block.len() {
            drbg.next_block();
        }
        let take = (buf.len() - written).min(drbg.block.len() - drbg.used);
        buf[written..written + take]
            .copy_from_slice(&drbg.block[drbg.used..drbg.used + take]);
        drbg.used += take;
        drbg.bytes_since_reseed += take;
        written += take;
    }
    Ok(())
}

/// Random source capabilities.
pub fn caps() -> RandomCaps {
    RandomCaps {
        hw_rdrand: crate::hal::has_rdrand() as u8,
        hw_rdseed: crate::hal::has_rdseed() as u8,
        pool_ready: {
            let mut drbg = DRBG.lock();
            drbg.ensure_seeded();
            drbg.seeded as u8
        },
        _pad: 0,
    }
}

/// Seed the pool and create `\Device\Random`.
pub fn init() {
    DRBG.lock().ensure_seeded();
    let _ = crate::object::namespace::ob_create_directory("\\Device\\Random");
    if let Ok(id) = crate::object::ob_create_object(
        crate::object::ObType::Device,
        "Random",
        DEVICE_NATIVE_ID,
        0,
        None,
    ) {
        let _ = crate::object::namespace::ob_insert_object("\\Device\\Random", id);
    }
}

fn reset_for_test() {
    *DRBG.lock() = Drbg::new();
}

pub fn register_tests() {
    use crate::{test_case, test_eq, test_ne, test_true};

    test_case!("random_chacha20_rfc8439_block", {
        // RFC 8439 §2.3.2 block function vector.
        let mut key = [0u8; 32];
        for (i, b) in key.iter_mut().enumerate() {
            *b = i as u8;
        }
        let nonce = [0, 0, 0, 9, 0, 0, 0, 0x4a, 0, 0, 0, 0];
        let block = chacha20_block(&key, 1, &nonce);
        let expected = [
            0x10, 0xf1, 0xe7, 0xe4, 0xd1, 0x3b, 0x59, 0x15, 0x50, 0x0f, 0xdd, 0x1f, 0xa3, 0x20,
            0x71, 0xc4, 0xc7, 0xd1, 0xf4, 0xc7, 0x33, 0xc0, 0x68, 0x03, 0x04, 0x22, 0xaa, 0x9a,
            0xc3, 0xd4, 0x6c, 0x4e, 0xd2, 0x82, 0x64, 0x46, 0x07, 0x9f, 0xaa, 0x09, 0x14, 0xc2,
            0xd7, 0x05, 0xd9, 0x8b, 0x02, 0xa2, 0xb5, 0x12, 0x9c, 0xd1, 0xde, 0x16, 0x4e, 0xb9,
            0xcb, 0xd0, 0x83, 0xe8, 0xa2, 0x50, 0x3c, 0x4e,
        ];
        test_eq!(block, expected);
    });

    test_case!("random_fill_is_seeded_and_varies", {
        reset_for_test();
        test_eq!(caps().pool_ready, 1);
        let mut a = [0u8; 64];
        let mut b = [0u8; 64];
        test_true!(fill(&mut a).is_ok());
        test_true!(fill(&mut b).is_ok());
        test_ne!(a, b);
        test_true!(a.iter().any(|v| *v != 0));
        // The pool keeps producing after a reseed.
        let mut c = [0u8; 128];
        test_true!(fill(&mut c).is_ok());
        test_true!(c.iter().any(|v| *v != c[0]));
    });

    test_case!("random_rejects_oversized_reads", {
        reset_for_test();
        let mut big = alloc::vec![0u8; MAX_READ + 1];
        test_eq!(fill(&mut big), Err(RngError::TooLarge));
        let mut ok = alloc::vec![0u8; MAX_READ];
        test_true!(fill(&mut ok).is_ok());
        // A zero-length request is a no-op, not an error.
        test_true!(fill(&mut []).is_ok());
    });

    test_case!("random_caps_reports_hardware", {
        let caps = caps();
        // x86_64 VMs used by the project expose RDRAND; do not hard-fail on
        // CPUs that do not, only require a seeded pool.
        test_eq!(caps.pool_ready, 1);
        test_true!(caps.hw_rdrand <= 1);
        test_true!(caps.hw_rdseed <= 1);
        test_eq!(caps._pad, 0);
    });
}
